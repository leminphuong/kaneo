#!/usr/bin/env bash
#
# Deploy this Kaneo fork on an Ubuntu server with Docker Compose.
#
# Run it from the repository root on the server:
#   bash scripts/deploy/deploy.sh
#
# It is safe to re-run: an existing .env is never overwritten, so re-running
# after `git pull` rebuilds and restarts with the same secrets and data.
#
# The bundled image serves the web app and the API on one port (5173) and runs
# database migrations on startup, so there is no separate migration step.

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$REPO_ROOT"

BLUE=$'\033[0;34m'; GREEN=$'\033[0;32m'; YELLOW=$'\033[1;33m'; RED=$'\033[0;31m'; NC=$'\033[0m'
step() { printf '%s==>%s %s\n' "$BLUE" "$NC" "$1"; }
ok()   { printf '%s  ok%s %s\n' "$GREEN" "$NC" "$1"; }
warn() { printf '%s  !!%s %s\n' "$YELLOW" "$NC" "$1"; }
die()  { printf '%s ERROR%s %s\n' "$RED" "$NC" "$1" >&2; exit 1; }

# --- sudo -----------------------------------------------------------------
if [ "$(id -u)" -eq 0 ]; then
  SUDO=""
elif command -v sudo >/dev/null 2>&1; then
  SUDO="sudo"
else
  die "Run as root or install sudo."
fi

# --- docker ---------------------------------------------------------------
step "Checking Docker"
if ! command -v docker >/dev/null 2>&1; then
  warn "Docker is not installed; installing from get.docker.com"
  curl -fsSL https://get.docker.com | $SUDO sh
  $SUDO usermod -aG docker "$(id -un)" || true
  warn "Added $(id -un) to the docker group. Log out and back in to use docker without sudo."
fi

if ! docker compose version >/dev/null 2>&1; then
  die "The Docker Compose v2 plugin is missing. Install docker-compose-plugin and re-run."
fi

DOCKER="docker"
if ! docker info >/dev/null 2>&1; then
  DOCKER="$SUDO docker"
  $DOCKER info >/dev/null 2>&1 || die "Cannot talk to the Docker daemon."
fi
ok "$($DOCKER --version)"

# --- build headroom -------------------------------------------------------
# The web build runs Vite and TypeScript; on a 1 GB droplet it gets OOM-killed
# and the failure surfaces as an unhelpful "exit code 137" mid-build.
step "Checking memory available for the build"
mem_total_kb=$(awk '/^MemTotal:/ {print $2}' /proc/meminfo)
swap_total_kb=$(awk '/^SwapTotal:/ {print $2}' /proc/meminfo)
total_mb=$(( (mem_total_kb + swap_total_kb) / 1024 ))
if [ "$total_mb" -lt 3500 ]; then
  warn "Only ${total_mb} MB of RAM + swap. The web build needs roughly 4 GB and may be killed."
  warn "Add swap first, for example:"
  warn "  sudo fallocate -l 4G /swapfile && sudo chmod 600 /swapfile"
  warn "  sudo mkswap /swapfile && sudo swapon /swapfile"
  warn "  echo '/swapfile none swap sw 0 0' | sudo tee -a /etc/fstab"
  if [ "${KANEO_ASSUME_YES:-}" = "1" ]; then
    warn "KANEO_ASSUME_YES=1, continuing anyway."
  elif [ -t 0 ]; then
    read -r -p "Continue anyway? [y/N] " reply
    [[ "$reply" =~ ^[Yy]$ ]] || exit 1
  else
    # Run from CI over SSH there is no one to answer, and stdin is already
    # spent on the remote script. Stopping here beats letting the OOM killer
    # pick a victim, which on a shared box can be another service entirely.
    die "Not enough memory and nothing attached to ask. Add swap, or set KANEO_ASSUME_YES=1 to build anyway."
  fi
else
  ok "${total_mb} MB RAM + swap"
fi

# --- .env -----------------------------------------------------------------
step "Checking .env"
if [ -f .env ]; then
  ok ".env already exists; leaving it untouched"
  missing=""
  for key in KANEO_CLIENT_URL AUTH_SECRET POSTGRES_PASSWORD; do
    grep -qE "^${key}=.+" .env || missing="$missing $key"
  done
  [ -z "$missing" ] || die "These are empty or missing in .env:$missing"
else
  public_url="${KANEO_PUBLIC_URL:-}"
  if [ -z "$public_url" ] && [ -t 0 ]; then
    echo "Public URL users will open, including the scheme."
    echo "Examples: https://kaneo.example.com   or   http://203.0.113.10:5173"
    read -r -p "Public URL: " public_url
  fi
  [ -n "$public_url" ] || die \
    "A public URL is required. Interactively you are asked for it; from CI set KANEO_PUBLIC_URL."
  case "$public_url" in
    http://*|https://*) ;;
    *) die "The URL must start with http:// or https://" ;;
  esac
  public_url="${public_url%/}"

  # openssl ships with Ubuntu; fall back to /dev/urandom if it somehow does not.
  gen_hex() {
    if command -v openssl >/dev/null 2>&1; then openssl rand -hex "$1"
    else head -c "$1" /dev/urandom | od -An -tx1 | tr -d ' \n'; fi
  }

  umask 077
  cat > .env <<EOF
# Generated by scripts/deploy/deploy.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# Keep this file out of version control: it holds this instance's secrets.
KANEO_CLIENT_URL=$public_url

POSTGRES_DB=kaneo
POSTGRES_USER=kaneo
POSTGRES_PASSWORD=$(gen_hex 24)

# Sessions are signed with this. Changing it logs everyone out.
AUTH_SECRET=$(gen_hex 32)

# ---------------------------------------------------------------------------
# Image and file uploads - Cloudflare R2 (S3-compatible API)
#
# Uncomment all six and fill in your values to turn uploads on. Until then,
# uploading an image in a task description or comment fails with "S3 uploads
# are not configured"; everything else works.
#
# The browser PUTs straight to S3_ENDPOINT with a presigned URL, so the bucket
# needs a CORS rule allowing PUT from $public_url. See scripts/deploy/README.md.
#
# S3_ENDPOINT must be the R2 *S3 API* endpoint, not the public r2.dev domain.
# ---------------------------------------------------------------------------
#S3_ENDPOINT=https://<ACCOUNT_ID>.r2.cloudflarestorage.com
#S3_BUCKET=kaneo-uploads
#S3_ACCESS_KEY_ID=<R2_ACCESS_KEY_ID>
#S3_SECRET_ACCESS_KEY=<R2_SECRET_ACCESS_KEY>
# R2 ignores regions, but the SDK requires one and Cloudflare documents "auto".
#S3_REGION=auto
# R2 is virtual-hosted style. The code default is true (for MinIO), so setting
# this explicitly is what keeps R2 working.
#S3_FORCE_PATH_STYLE=false
EOF
  ok "Wrote .env with a generated database password and AUTH_SECRET"
  warn "Uploads are off until you fill in the R2 block in .env (see scripts/deploy/README.md)."
fi

# --- build and start ------------------------------------------------------
COMPOSE="$DOCKER compose -f compose.yml -f compose.build.yml"

step "Building the image from this working tree (first build takes several minutes)"
$COMPOSE build

step "Starting services"
$COMPOSE up -d

# --- wait for health ------------------------------------------------------
# Startup runs the database migrations, so the first boot after a schema
# change is far slower than a restart. Override with KANEO_HEALTH_TIMEOUT.
HEALTH_TIMEOUT="${KANEO_HEALTH_TIMEOUT:-900}"
step "Waiting for Kaneo to become healthy (up to $((HEALTH_TIMEOUT / 60)) min)"
deadline=$(( $(date +%s) + HEALTH_TIMEOUT ))
while :; do
  if curl -fsS -o /dev/null http://127.0.0.1:5173/api/health 2>/dev/null; then
    ok "Kaneo is responding on port 5173"
    break
  fi
  if [ "$(date +%s)" -ge "$deadline" ]; then
    printf '\n'
    warn "Did not become healthy within $((HEALTH_TIMEOUT / 60)) minutes. Recent logs:"
    $COMPOSE logs --tail 60 kaneo
    die "Startup failed."
  fi
  printf '.'
  sleep 3
done

client_url=$(grep -E '^KANEO_CLIENT_URL=' .env | cut -d= -f2-)
printf '\n'
ok "Deployed."
echo
echo "  Open:      $client_url"
echo "  Logs:      docker compose -f compose.yml -f compose.build.yml logs -f kaneo"
echo "  Update:    git pull && bash scripts/deploy/deploy.sh"
echo "  Stop:      docker compose -f compose.yml -f compose.build.yml down"
echo
echo "The first account registered becomes the instance administrator."
echo "Put a TLS reverse proxy in front before exposing this publicly;"
echo "see scripts/deploy/README.md."
